# @brief Reproduce a patch-only SpotX adapter from a hash-pinned MIT source.
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / 'third_party' / 'spotx'
UPSTREAM_SHA = '0d2a747b5c8ac07df2dd4771463ea336bbdd08153adb7043bf899ad0dd865e57'


def between(source, start, end):
    if source.count(start) != 1 or source.count(end) != 1:
        raise ValueError('Upstream section boundary changed')
    return source.split(start, 1)[1].split(end, 1)[0]


def build():
    raw = (DIRECTORY / 'upstream-run.ps1').read_bytes()
    if hashlib.sha256(raw).hexdigest() != UPSTREAM_SHA:
        raise ValueError('SpotX source digest mismatch')
    source = raw.decode('utf-8-sig').replace('\r\n', '\n')
    # These sections contain local archive/binary functions and their patch
    # calls only. The upstream installer, downloads, Defender, Store removal,
    # shortcuts, process killing and startup configuration are excluded.
    functions = 'function Get-JsonValue {' + between(
        source, 'function Get-JsonValue {', 'function Get-SpotXResources {')
    archive = 'if ($test_spa) {' + between(
        source, 'if ($test_spa) {', '# Delete all files except "en" and "ru"')
    binary = '$ANSI = [Text.Encoding]::GetEncoding(1251)\n$old =' + between(
        source, '$ANSI = [Text.Encoding]::GetEncoding(1251)\n$old =', '# fix login for old versions')
    calls = archive + '\n' + binary
    calls = '\n'.join('    throw "SpotX patch stopped before completion"' if line.strip().lower() == 'exit'
                      else line for line in calls.splitlines())
    calls = calls.replace('$null = Set-BlockSlotsBinaryPatch -FilePath $spotifyDll',
                          'if (-not (Set-BlockSlotsBinaryPatch -FilePath $spotifyDll)) { throw "SpotX block-slots patch failed" }')
    calls = calls.replace('$null = Set-CrossfadeEnabledBinaryPatch -FilePath $spotifyDll -TargetVersion ([version]$offline)',
                          'if (-not (Set-CrossfadeEnabledBinaryPatch -FilePath $spotifyDll -TargetVersion ([version]$offline))) { throw "SpotX crossfade patch failed" }')
    for command in ('Invoke-WebRequest', 'Invoke-RestMethod', 'Add-MpPreference', 'Get-AppxPackage',
                    'Remove-AppxPackage', 'Start-Process', 'Stop-Process', 'Read-Host', 'New-ItemProperty'):
        if command.lower() in (functions + calls).lower():
            raise ValueError(f'Unexpected non-patch operation: {command}')
    header = ('# Generated by scripts/build_spotx_adapter.py; do not edit.\n'
              '# Derived from SpotX commit 3cfbdfd1fac3dc755155e434116e28b51acfec07.\n'
              '# Copyright (c) 2021-2026 amd64fox. MIT; see LICENSE.\n')
    (DIRECTORY / 'patch-functions.ps1').write_text(header + functions, encoding='utf-8-sig')
    (DIRECTORY / 'patch-calls.ps1').write_text(header + calls + '\n', encoding='utf-8-sig')
    manifest = {'repository': 'https://github.com/SpotX-Official/SpotX',
                'revision': '3cfbdfd1fac3dc755155e434116e28b51acfec07', 'license': 'MIT',
                'files': {name: hashlib.sha256((DIRECTORY / name).read_bytes()).hexdigest()
                          for name in ('upstream-run.ps1', 'patches.json', 'en.ps1', 'LICENSE',
                                       'patch-functions.ps1', 'patch-calls.ps1')}}
    (DIRECTORY / 'upstream.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    build()
